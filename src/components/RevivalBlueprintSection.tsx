import React, { useState } from 'react';
import { Compass, CheckCircle2, Copy, Check, FileDown, GitPullRequest, ChevronDown, ChevronUp, Layers, AlertCircle } from 'lucide-react';
import { RevivalTask, BlueprintCategory } from '../types/archive';

interface RevivalBlueprintSectionProps {
  tasks: RevivalTask[];
}

export const RevivalBlueprintSection: React.FC<RevivalBlueprintSectionProps> = ({ tasks }) => {
  const [taskStates, setTaskStates] = useState<Record<string, RevivalTask['status']>>({});
  const [expandedTaskId, setExpandedTaskId] = useState<string | null>(tasks[0]?.id || null);
  const [copiedTaskId, setCopiedTaskId] = useState<string | null>(null);
  const [draftIssueModalTask, setDraftIssueModalTask] = useState<RevivalTask | null>(null);
  const [categoryFilter, setCategoryFilter] = useState<string>('all');

  const categories: Array<{ id: string; label: string }> = [
    { id: 'all', label: 'All Tasks' },
    { id: 'fix_first', label: 'Fix First (P0)' },
    { id: 'complete_feature', label: 'Complete Features' },
    { id: 'add_tests', label: 'Tests & Benches' },
    { id: 'improve_architecture', label: 'Architecture' },
    { id: 'good_first_issue', label: 'Good First Issues' }
  ];

  const filteredTasks = tasks.filter(t => {
    if (categoryFilter === 'all') return true;
    return t.category === categoryFilter;
  });

  const handleStatusChange = (taskId: string, status: RevivalTask['status']) => {
    setTaskStates(prev => ({ ...prev, [taskId]: status }));
  };

  const handleCopyTask = (task: RevivalTask, e: React.MouseEvent) => {
    e.stopPropagation();
    const text = `## [REQUIEM REVIVAL] ${task.priority}: ${task.title}
Difficulty: ${task.estimatedDifficulty}
Category: ${task.category}
Reason: ${task.reason}
Evidence: ${task.supportingEvidence}

### Implementation Steps:
${task.suggestedSteps.map(s => `- ${s}`).join('\n')}

### Expected Outcome:
${task.expectedOutcome}

### Acceptance Criteria:
${task.acceptanceCriteria.map(a => `- [ ] ${a}`).join('\n')}`;

    navigator.clipboard.writeText(text);
    setCopiedTaskId(task.id);
    setTimeout(() => setCopiedTaskId(null), 2000);
  };

  const handleExportMarkdown = () => {
    const md = `# REQUIEM REVIVAL BLUEPRINT
Project: HyperFlow Engine
Generated by: REQUIEM Digital Archaeology Platform
Timestamp: ${new Date().toISOString()}

${tasks
  .map(
    t => `## [${t.priority}] ${t.title}
- **Category:** ${t.category}
- **Difficulty:** ${t.estimatedDifficulty}
- **Status:** ${taskStates[t.id] || t.status}
- **Reason:** ${t.reason}
- **Evidence Reference:** ${t.supportingEvidence}

### Steps:
${t.suggestedSteps.map(s => `1. ${s}`).join('\n')}

### Acceptance Criteria:
${t.acceptanceCriteria.map(a => `- [ ] ${a}`).join('\n')}
`
  )
  .join('\n---\n\n')}`;

    const blob = new Blob([md], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'requiem-revival-blueprint.md';
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <section id="blueprint" className="relative py-28 bg-[#080712] overflow-hidden border-t border-[#17102E]">
      <div className="max-w-7xl mx-auto px-6 relative z-10">
        {/* Section Header */}
        <div className="flex flex-col lg:flex-row lg:items-end justify-between gap-6 mb-16">
          <div className="max-w-3xl">
            <div className="flex items-center gap-2 text-xs tracking-[0.2em] text-[#D7B878] uppercase font-mono mb-4">
              <span className="w-6 h-[1px] bg-[#D7B878]" />
              <span>Section 09 · Actionable Resurrection</span>
            </div>
            <h2 className="text-3xl sm:text-4xl lg:text-5xl font-extrabold text-[#ECEAF5] tracking-tight font-display mb-4">
              THE REVIVAL BLUEPRINT
            </h2>
            <p className="text-base text-[#A8A4B8] leading-relaxed font-light">
              Transform archaeological insights into concrete pull requests. Prioritized by stability impact, with verified acceptance criteria and draft GitHub issues.
            </p>
          </div>

          <button
            onClick={handleExportMarkdown}
            className="flex items-center gap-2 px-4 py-2.5 text-xs font-mono font-semibold uppercase text-white bg-[#17102E] hover:bg-[#30215B] border border-[#30215B] hover:border-[#956BFF] rounded-lg transition-colors shrink-0"
          >
            <FileDown className="w-4 h-4 text-[#75D8FF]" />
            <span>Export Blueprint (MD)</span>
          </button>
        </div>

        {/* Filter categories */}
        <div className="flex flex-wrap items-center gap-2 mb-8">
          {categories.map(cat => (
            <button
              key={cat.id}
              onClick={() => setCategoryFilter(cat.id)}
              className={`px-3 py-1.5 text-xs font-medium rounded-md transition-colors ${
                categoryFilter === cat.id
                  ? 'bg-[#956BFF] text-white'
                  : 'bg-[#17102E] text-[#A8A4B8] hover:text-[#ECEAF5]'
              }`}
            >
              {cat.label}
            </button>
          ))}
        </div>

        {/* Tasks List */}
        <div className="space-y-4">
          {filteredTasks.map(task => {
            const isExpanded = expandedTaskId === task.id;
            const currentStatus = taskStates[task.id] || task.status;

            return (
              <div
                key={task.id}
                className={`rounded-xl border transition-all duration-200 overflow-hidden ${
                  currentStatus === 'completed'
                    ? 'bg-[#0a1410] border-emerald-900/40'
                    : currentStatus === 'accepted'
                    ? 'bg-[#17102E] border-[#956BFF]/60'
                    : currentStatus === 'dismissed'
                    ? 'bg-[#0f0b21]/40 border-[#30215B]/30 opacity-60'
                    : 'bg-[#0f0b21] border-[#30215B]/60 hover:border-[#30215B]'
                }`}
              >
                {/* Task Accordion Bar */}
                <div
                  onClick={() => setExpandedTaskId(isExpanded ? null : task.id)}
                  className="p-6 cursor-pointer flex flex-col md:flex-row md:items-center justify-between gap-4"
                >
                  <div className="flex items-start md:items-center gap-4">
                    <span
                      className={`px-2.5 py-1 text-xs font-mono font-bold rounded shrink-0 ${
                        task.priority === 'P0'
                          ? 'bg-red-500/20 text-red-400 border border-red-500/40'
                          : task.priority === 'P1'
                          ? 'bg-[#956BFF]/20 text-[#75D8FF] border border-[#956BFF]/40'
                          : 'bg-[#17102E] text-[#A8A4B8] border border-[#30215B]'
                      }`}
                    >
                      {task.priority}
                    </span>

                    <div>
                      <h3 className="text-base font-bold text-[#ECEAF5] font-display">
                        {task.title}
                      </h3>
                      <div className="flex items-center gap-2 text-xs font-mono text-[#A8A4B8] mt-1">
                        <span className="capitalize">{task.category.replace('_', ' ')}</span>
                        <span>·</span>
                        <span>Estimated: {task.estimatedDifficulty}</span>
                        <span>·</span>
                        <span className="text-[#75D8FF]">{task.supportingEvidence}</span>
                      </div>
                    </div>
                  </div>

                  <div className="flex items-center gap-3 shrink-0">
                    {/* Status badge / toggle */}
                    <select
                      value={currentStatus}
                      onChange={e => {
                        e.stopPropagation();
                        handleStatusChange(task.id, e.target.value as RevivalTask['status']);
                      }}
                      onClick={e => e.stopPropagation()}
                      className="bg-[#080712] border border-[#30215B] text-xs font-mono text-[#ECEAF5] rounded px-2.5 py-1 focus:outline-none focus:border-[#956BFF]"
                    >
                      <option value="pending">Pending</option>
                      <option value="accepted">Accepted</option>
                      <option value="completed">Completed</option>
                      <option value="dismissed">Dismissed</option>
                    </select>

                    <button
                      onClick={e => handleCopyTask(task, e)}
                      className="p-2 text-[#A8A4B8] hover:text-white rounded hover:bg-[#17102E]"
                      title="Copy Task"
                    >
                      {copiedTaskId === task.id ? <Check className="w-4 h-4 text-emerald-400" /> : <Copy className="w-4 h-4" />}
                    </button>

                    <button
                      onClick={e => {
                        e.stopPropagation();
                        setDraftIssueModalTask(task);
                      }}
                      className="p-2 text-[#75D8FF] hover:text-white rounded hover:bg-[#17102E]"
                      title="Generate Draft Issue"
                    >
                      <GitPullRequest className="w-4 h-4" />
                    </button>

                    {isExpanded ? (
                      <ChevronUp className="w-5 h-5 text-[#A8A4B8]" />
                    ) : (
                      <ChevronDown className="w-5 h-5 text-[#A8A4B8]" />
                    )}
                  </div>
                </div>

                {/* Expanded Details */}
                {isExpanded && (
                  <div className="px-6 pb-6 pt-2 border-t border-[#17102E] bg-[#080712]/50 space-y-6">
                    <div>
                      <div className="text-xs font-mono uppercase tracking-wider text-[#956BFF] mb-1">
                        Reason For Recommendation
                      </div>
                      <p className="text-xs text-[#ECEAF5] leading-relaxed">
                        {task.reason}
                      </p>
                    </div>

                    <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                      {/* Implementation steps */}
                      <div className="p-4 rounded-lg bg-[#0f0b21] border border-[#30215B]">
                        <div className="text-xs font-mono uppercase tracking-wider text-[#75D8FF] mb-3">
                          Suggested Implementation Steps
                        </div>
                        <ol className="space-y-2 text-xs text-[#A8A4B8] list-decimal list-inside leading-relaxed">
                          {task.suggestedSteps.map((step, idx) => (
                            <li key={idx} className="pl-1">
                              {step}
                            </li>
                          ))}
                        </ol>
                      </div>

                      {/* Acceptance criteria */}
                      <div className="p-4 rounded-lg bg-[#0f0b21] border border-[#30215B]">
                        <div className="text-xs font-mono uppercase tracking-wider text-emerald-400 mb-3">
                          Acceptance Criteria
                        </div>
                        <ul className="space-y-2 text-xs text-[#A8A4B8]">
                          {task.acceptanceCriteria.map((crit, idx) => (
                            <li key={idx} className="flex items-start gap-2">
                              <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400 shrink-0 mt-0.5" />
                              <span>{crit}</span>
                            </li>
                          ))}
                        </ul>
                      </div>
                    </div>

                    <div className="flex flex-wrap items-center justify-between gap-4 pt-4 border-t border-[#17102E] text-xs font-mono text-[#A8A4B8]">
                      <div>
                        Expected Outcome: <strong className="text-[#ECEAF5]">{task.expectedOutcome}</strong>
                      </div>
                      <button
                        onClick={() => setDraftIssueModalTask(task)}
                        className="text-[#956BFF] hover:underline"
                      >
                        Draft GitHub Issue Template →
                      </button>
                    </div>
                  </div>
                )}
              </div>
            );
          })}
        </div>
      </div>

      {/* Draft GitHub Issue Modal */}
      {draftIssueModalTask && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm animate-in fade-in">
          <div className="relative w-full max-w-2xl bg-[#0f0b21] border border-[#956BFF] rounded-xl p-6 shadow-2xl">
            <div className="flex items-center justify-between mb-4">
              <div className="flex items-center gap-2 text-xs font-mono text-[#75D8FF]">
                <GitPullRequest className="w-4 h-4" />
                <span>Draft GitHub Issue Template</span>
              </div>
              <button
                onClick={() => setDraftIssueModalTask(null)}
                className="text-[#A8A4B8] hover:text-white"
              >
                ✕
              </button>
            </div>

            <div className="mb-4">
              <label className="text-xs font-mono text-[#A8A4B8] block mb-1">Issue Title</label>
              <input
                type="text"
                readOnly
                value={`[Revival] ${draftIssueModalTask.priority}: ${draftIssueModalTask.title}`}
                className="w-full bg-[#080712] border border-[#30215B] rounded px-3 py-2 text-xs font-mono text-[#ECEAF5]"
              />
            </div>

            <div className="mb-6">
              <label className="text-xs font-mono text-[#A8A4B8] block mb-1">Issue Markdown Body</label>
              <textarea
                readOnly
                rows={10}
                value={`### Problem Description
${draftIssueModalTask.reason}

### Supporting Evidence
Identified in: \`${draftIssueModalTask.supportingEvidence}\`

### Proposed Changes
${draftIssueModalTask.suggestedSteps.map(s => `- ${s}`).join('\n')}

### Acceptance Criteria
${draftIssueModalTask.acceptanceCriteria.map(a => `- [ ] ${a}`).join('\n')}

---
*Generated by REQUIEM: The Ghost Archive (Hacktoberfest 2026)*`}
                className="w-full bg-[#080712] border border-[#30215B] rounded p-3 text-xs font-mono text-[#A8A4B8] leading-relaxed resize-none"
              />
            </div>

            <div className="flex items-center justify-end gap-3">
              <button
                onClick={() => {
                  navigator.clipboard.writeText(
                    `[Revival] ${draftIssueModalTask.priority}: ${draftIssueModalTask.title}\n\n` +
                    `### Problem Description\n${draftIssueModalTask.reason}\n\n` +
                    `### Proposed Changes\n${draftIssueModalTask.suggestedSteps.map(s => `- ${s}`).join('\n')}`
                  );
                  alert('Copied GitHub Issue template to clipboard!');
                  setDraftIssueModalTask(null);
                }}
                className="px-4 py-2 text-xs font-semibold uppercase tracking-wider text-white bg-[#956BFF] hover:bg-[#8555f5] rounded-md transition-colors"
              >
                Copy to Clipboard
              </button>
            </div>
          </div>
        </div>
      )}
    </section>
  );
};
